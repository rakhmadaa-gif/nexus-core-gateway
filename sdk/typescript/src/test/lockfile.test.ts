import { test } from "node:test";
import * as assert from "node:assert/strict";
import {
  parseLockfile,
  preparePackages,
  toFitnessPayload,
  dedupePackages,
  detectLockfileFormat,
} from "../lockfile";

test("package-lock v2/v3 flat packages map", () => {
  const content = JSON.stringify({
    lockfileVersion: 3,
    packages: {
      "": { name: "root" },
      "node_modules/lodash": { version: "4.17.20", dev: true },
      "node_modules/express": { version: "4.18.2" },
      "node_modules/@scope/util": { version: "1.0.0" },
    },
  });
  const r = parseLockfile("package-lock.json", content);
  assert.equal(r.error, undefined);
  assert.equal(r.packages.length, 3);
  const prep = preparePackages(r.packages, 250);
  assert.equal(prep.packages.length, 2); // lodash dev excluded
  assert.equal(prep.excludedDev, 1);
  // deterministic sort: @scope/util before express
  assert.equal(prep.packages[0].name, "@scope/util");
  const payload = toFitnessPayload(prep.packages);
  assert.deepEqual(payload[0], { name: "@scope/util", ecosystem: "npm", version: "1.0.0" });
});

test("package-lock v1 nested dependencies", () => {
  const content = JSON.stringify({
    lockfileVersion: 1,
    dependencies: {
      express: { version: "4.18.2", requires: {} },
      mocha: { version: "10.0.0", dev: true, dependencies: { diff: { version: "5.0.0" } } },
    },
  });
  const r = parseLockfile("package-lock.json", content);
  assert.equal(r.packages.length, 3);
  const diff = r.packages.find((p) => p.name === "diff");
  assert.ok(diff?.dev === true, "nested dep of dev dep inherits dev");
});

test("requirements.txt with pins, ranges, comments, markers", () => {
  const content = `# comment\nrequests==2.31.0\nflask >= 2.0  # trailing\n--index-url https://pypi.org/simple\n; env marker stripped\npytest==7.4.0 ; python_version > "3.8"\n`;
  const r = parseLockfile("requirements.txt", content);
  const names = r.packages.map((p) => p.name);
  assert.ok(names.includes("requests"));
  assert.ok(names.includes("flask"));
  assert.ok(names.includes("pytest"));
  assert.ok(!names.includes("--index-url"));
  const flask = r.packages.find((p) => p.name === "flask");
  assert.equal(flask?.version, undefined);
  assert.equal(flask?.version_source, "unpinned");
});

test("yarn v1 lockfile", () => {
  const content = `# yarn lockfile v1\n\nlodash@^4.17.20, lodash@^4.17.21:\n  version "4.17.21"\n  resolved "https://registry.yarnpkg.com/lodash/-/lodash-4.17.21.tgz"\n\n"@scope/util@^1.0.0":\n  version "1.2.0"\n`;
  const r = parseLockfile("yarn.lock", content);
  // dedupe collapses the two lodash aliases to one entry (same version)
  assert.equal(r.packages.length, 2);
  const lodash = r.packages.find((p) => p.name === "lodash");
  assert.equal(lodash?.version, "4.17.21");
});

test("go.mod require blocks incl. indirect", () => {
  const content = `module example.com/app\n\ngo 1.21\n\nrequire (\n\tgithub.com/gin-gonic/gin v1.9.1\n\tgolang.org/x/text v0.13.0 // indirect\n)\n\nrequire github.com/stretchr/testify v1.8.4\n`;
  const r = parseLockfile("go.mod", content);
  assert.equal(r.packages.length, 3);
  const indirect = r.packages.find((p) => p.name === "golang.org/x/text");
  assert.equal(indirect?.dev, true);
});

test("Cargo.lock stanzas", () => {
  const content = `# This file is automatically @generated by Cargo.\nversion = 3\n\n[[package]]\nname = "serde"\nversion = "1.0.188"\nsource = "registry+https://github.com/rust-lang/crates.io-index"\n\n[[package]]\nname = "myapp"\nversion = "0.1.0"\n`;
  const r = parseLockfile("Cargo.lock", content);
  assert.equal(r.packages.length, 2);
  const serde = r.packages.find((p) => p.name === "serde");
  assert.equal(serde?.ecosystem, "crates.io");
  assert.equal(serde?.version, "1.0.188");
});

test("package.json manifest entries are unpinned", () => {
  const content = JSON.stringify({
    name: "app",
    dependencies: { express: "^4.18.2" },
    devDependencies: { typescript: "^5.0.0" },
  });
  const r = parseLockfile("package.json", content);
  const express = r.packages.find((p) => p.name === "express");
  assert.equal(express?.version_source, "manifest");
  assert.equal(express?.version, undefined);
});

test("capPackages truncation flag", () => {
  const content = JSON.stringify({
    name: "app",
    dependencies: Object.fromEntries([...Array(300).keys()].map((i) => [`pkg${i}`, "^1.0.0"])),
  });
  const r = parseLockfile("package.json", content);
  const prep = preparePackages(r.packages, 250);
  assert.equal(prep.capped, true);
  assert.equal(prep.packages.length, 250);
});

test("dedupe case-insensitive on name keeps first occurrence", () => {
  const a = { name: "Lodash", ecosystem: "npm", version: "4.17.21", version_source: "lockfile" as const };
  const b = { name: "lodash", ecosystem: "npm", version: "4.17.21", version_source: "lockfile" as const };
  const out = dedupePackages([a, b]);
  assert.equal(out.length, 1);
  assert.equal(out[0].name, "Lodash");
});

test("format detection by content sniffing", () => {
  assert.equal(detectLockfileFormat(undefined, "# yarn lockfile v1\n\n"), "yarn");
  assert.equal(detectLockfileFormat(undefined, "module example.com/app\n\ngo 1.21\n"), "go-mod");
  assert.equal(detectLockfileFormat(undefined, "[[package]]\nname = \"x\"\n"), "cargo");
  assert.equal(detectLockfileFormat(undefined, JSON.stringify({ lockfileVersion: 3, packages: {} })), "package-lock");
});
