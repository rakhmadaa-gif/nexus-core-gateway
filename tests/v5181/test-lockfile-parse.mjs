// v5.18.1 (Gas Bahasa) — unit tests for the PHP/Dart/Ruby lockfile parsers.
// Run: npx esbuild tests/v5181/test-lockfile-parse.mjs --bundle --platform=node --outfile=/tmp/t5181.js && node /tmp/t5181.js
import {
  detectLockfileFormat, parseLockfile,
} from "../../supabase/functions/hello-world/lockfile_parse.ts";

let pass = 0, fail = 0;
function T(name, cond, extra) {
  if (cond) { pass++; console.log(`PASS ${name}`); }
  else { fail++; console.log(`FAIL ${name}${extra ? " — " + JSON.stringify(extra) : ""}`); }
}

// -- composer.lock (PHP / Packagist) --
const composerLock = JSON.stringify({
  "_readme": ["This file is @generated"],
  "content-hash": "abc123def",
  "packages": [
    { "name": "guzzlehttp/guzzle", "version": "6.5.5" },
    { "name": "symfony/console", "version": "v5.4.20" },
  ],
  "packages-dev": [
    { "name": "phpunit/phpunit", "version": "9.5.26" },
    { "name": "friendsofphp/php-cs-fixer", "version": "dev-master" },
  ],
  "platform": { "php": ">=8.0" },
});
let r = parseLockfile("composer.lock", composerLock);
T("composer format", r.format === "composer" && !r.error, r);
T("composer count (dev included, disclosed)", r.packages.length === 4, r.packages);
const gz = r.packages.find((p) => p.name === "guzzlehttp/guzzle");
T("composer runtime pkg", gz && gz.version === "6.5.5" && gz.dev === undefined && gz.ecosystem === "Packagist" && gz.version_source === "lockfile", gz);
const sc = r.packages.find((p) => p.name === "symfony/console");
T("composer v-prefix stripped", sc && sc.version === "5.4.20", sc);
const pu = r.packages.find((p) => p.name === "phpunit/phpunit");
T("composer dev flag", pu && pu.dev === true && pu.version === "9.5.26", pu);
const cs = r.packages.find((p) => p.name === "friendsofphp/php-cs-fixer");
T("composer dev-branch unpinned", cs && cs.dev === true && !("version" in cs), cs);

// detection: filename + content sniff (no filename)
T("composer detect by filename", detectLockfileFormat("composer.lock", composerLock) === "composer");
T("composer detect by sniff", detectLockfileFormat(undefined, composerLock) === "composer");

// -- composer.json manifest (PHP) --
const composerJson = JSON.stringify({
  "name": "acme/app",
  "require": { "php": "^8.1", "ext-json": "*", "guzzlehttp/guzzle": "^7.0", "monolog/monolog": "^3.0" },
  "require-dev": { "phpunit/phpunit": "^9.0" },
});
r = parseLockfile("composer.json", composerJson);
T("composer-json format", r.format === "composer-json" && !r.error, r);
T("composer-json count (platform pkgs skipped)", r.packages.length === 3, r.packages);
T("composer-json unpinned (no version)", r.packages.every((p) => !("version" in p) && p.version_source === "manifest"), r.packages);
T("composer-json dev flag", r.packages.find((p) => p.name === "phpunit/phpunit")?.dev === true, r.packages);
T("composer-json detect by sniff", detectLockfileFormat(undefined, composerJson) === "composer-json");

// -- pubspec.lock (Dart / Pub) --
const pubspecLock = `# Generated by pub
# See https://dart.dev/tools/pub/glossary#lockfile
packages:
  args:
    dependency: transitive
    description:
      name: args
      sha256: "e4b1a48c8c1d3b6c8f0e1f2a3b4c5d6e7f8a9b0c"
      url: "https://pub.dev"
    source: hosted
    version: "2.4.2"
  flutter:
    dependency: "direct main"
    description: flutter
    source: sdk
    version: "0.0.0"
  flutter_test:
    dependency: "direct dev"
    description: flutter
    source: sdk
    version: "0.0.0"
  http:
    dependency: "direct main"
    description:
      name: http
      url: "https://pub.dev"
    source: hosted
    version: "1.1.0"
  build_runner:
    dependency: "transitive dev"
    description:
      name: build_runner
      url: "https://pub.dev"
    source: hosted
    version: "2.4.7"
sdks:
  dart: ">=3.0.0 <4.0.0"
  flutter: ">=3.10.0"
`;
r = parseLockfile("pubspec.lock", pubspecLock);
T("pubspec format", r.format === "pubspec" && !r.error, r);
T("pubspec count (sdk skipped)", r.packages.length === 3, r.packages);
const args = r.packages.find((p) => p.name === "args");
T("pubspec runtime transitive", args && args.version === "2.4.2" && args.dev === undefined && args.ecosystem === "Pub", args);
const http = r.packages.find((p) => p.name === "http");
T("pubspec direct main", http && http.version === "1.1.0" && http.dev === undefined, http);
const br = r.packages.find((p) => p.name === "build_runner");
T("pubspec transitive dev flag", br && br.dev === true && br.version === "2.4.7", br);
T("pubspec sdk skipped", !r.packages.some((p) => p.name === "flutter" || p.name === "flutter_test"), r.packages);
T("pubspec detect by filename", detectLockfileFormat("pubspec.lock", pubspecLock) === "pubspec");
T("pubspec detect by sniff", detectLockfileFormat(undefined, pubspecLock) === "pubspec");

// pubspec with ONLY sdk packages → zero packages → error (not silent empty success)
const pubspecSdkOnly = `packages:
  flutter:
    dependency: "direct main"
    description: flutter
    source: sdk
    version: "0.0.0"
sdks:
  dart: ">=3.0.0"
`;
r = parseLockfile("pubspec.lock", pubspecSdkOnly);
T("pubspec sdk-only → error", r.packages.length === 0 && typeof r.error === "string" && r.error.includes("zero packages"), r);

// -- Gemfile.lock (Ruby / RubyGems) --
const gemfileLock = `GEM
  remote: https://rubygems.org/
  specs:
    actionpack (7.0.8)
      rack (>= 2.2.3)
      rack-test (>= 0.6.3)
    nokogiri (1.13.10-x86_64-linux)
      racc (~> 1.4)
    rails (7.0.8)

GIT
  remote: https://github.com/foo/bar.git
  revision: abc123def
  specs:
    bar (1.0.0)

PLATFORMS
  x86_64-linux

DEPENDENCIES
  rails (~> 7.0)
  bar!

BUNDLED WITH
   2.4.10
`;
r = parseLockfile("Gemfile.lock", gemfileLock);
T("gemfile format", r.format === "gemfile" && !r.error, r);
T("gemfile count (nested constraints skipped, GIT section included)", r.packages.length === 4, r.packages);
const ap = r.packages.find((p) => p.name === "actionpack");
T("gemfile spec version", ap && ap.version === "7.0.8" && ap.ecosystem === "RubyGems" && ap.version_source === "lockfile", ap);
const noko = r.packages.find((p) => p.name === "nokogiri");
T("gemfile platform suffix stripped", noko && noko.version === "1.13.10", noko);
const bar = r.packages.find((p) => p.name === "bar");
T("gemfile GIT section pkg", bar && bar.version === "1.0.0", bar);
T("gemfile dev undefined (Bundler merges groups)", r.packages.every((p) => p.dev === undefined), r.packages);
T("gemfile detect by filename", detectLockfileFormat("Gemfile.lock", gemfileLock) === "gemfile");
T("gemfile detect by sniff", detectLockfileFormat(undefined, gemfileLock) === "gemfile");

// -- regression guards: old formats unaffected --
const pl3 = JSON.stringify({ lockfileVersion: 3, packages: { "": { name: "root" }, "node_modules/lodash": { version: "4.17.20" } } });
T("package-lock still detected", detectLockfileFormat("package-lock.json", pl3) === "package-lock");
T("package-lock sniff still wins over composer", detectLockfileFormat(undefined, pl3) === "package-lock");
const reqs = "flask==2.0.1\nrequests==2.31.0\n";
T("requirements not misdetected", detectLockfileFormat("requirements.txt", reqs) === "requirements" && detectLockfileFormat(undefined, reqs) === "requirements");
const pkgJson = JSON.stringify({ name: "x", dependencies: { lodash: "^4.0.0" } });
T("package.json still detected (composer-json first does not shadow)", detectLockfileFormat("package.json", pkgJson) === "package-json" && detectLockfileFormat(undefined, pkgJson) === "package-json");

// -- unrecognized still unrecognized --
T("unknown stays unknown", detectLockfileFormat(undefined, "hello world this is not a lockfile") === "unknown");
r = parseLockfile(undefined, "hello world this is not a lockfile");
T("unknown error message lists new formats", typeof r.error === "string" && r.error.includes("composer.lock") && r.error.includes("pubspec.lock") && r.error.includes("Gemfile.lock"), r.error);

console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail === 0 ? 0 : 1);
