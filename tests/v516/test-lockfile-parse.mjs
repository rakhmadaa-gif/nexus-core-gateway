// W7 / v5.16.0 — unit tests for lockfile_parse.ts (pure module).
// Run: npx esbuild tests/v516/test-lockfile-parse.mjs --bundle --platform=node --outfile=/tmp/t516.js && node /tmp/t516.js
import {
  detectLockfileFormat, parseLockfile, mergePackageLists, PACKAGES_MAX,
} from "../../supabase/functions/hello-world/lockfile_parse.ts";

let pass = 0, fail = 0;
function T(name, cond, extra) {
  if (cond) { pass++; console.log(`PASS ${name}`); }
  else { fail++; console.log(`FAIL ${name}${extra ? " — " + JSON.stringify(extra) : ""}`); }
}

// -- 1. package-lock v2/v3 (nested paths, dev flag, dedupe) --
const pl3 = JSON.stringify({
  lockfileVersion: 3,
  packages: {
    "": { name: "root" },
    "node_modules/lodash": { version: "4.17.20" },
    "node_modules/@scope/pkg": { version: "1.0.0", dev: true },
    "node_modules/a/node_modules/b": { version: "2.0.0" },
  },
});
let r = parseLockfile("package-lock.json", pl3);
T("pl3 format", r.format === "package-lock");
T("pl3 count", r.packages.length === 3, r.packages);
T("pl3 nested name", r.packages.some((p) => p.name === "b" && p.version === "2.0.0"));
T("pl3 scoped", r.packages.some((p) => p.name === "@scope/pkg" && p.dev === true));
T("pl3 src", r.packages.every((p) => p.version_source === "lockfile" && p.ecosystem === "npm"));

// -- 2. package-lock v1 (dependencies tree) --
const pl1 = JSON.stringify({
  lockfileVersion: 1,
  dependencies: { foo: { version: "1.2.3", dependencies: { bar: { version: "0.1.0", dev: true } } } },
});
r = parseLockfile("package-lock.json", pl1);
T("pl1 tree", r.packages.length === 2 && r.packages.some((p) => p.name === "bar" && p.dev === true), r.packages);

// -- 3. yarn.lock v1 (multi-alias, scoped) --
const yarn1 = `# yarn lockfile v1
lodash@^4.17.20, lodash@^4.17.21:
  version "4.17.21"
  resolved "https://registry.yarnpkg.com/lodash/-/lodash-4.17.21.tgz"

"@babel/core@^7.0.0":
  version "7.24.0"
`;
r = parseLockfile("yarn.lock", yarn1);
T("yarn1 format", r.format === "yarn");
T("yarn1 dedupe", r.packages.length === 2, r.packages);
T("yarn1 scoped", r.packages.some((p) => p.name === "@babel/core" && p.version === "7.24.0"));

// -- 4. yarn berry (quoted, npm: protocol, __metadata) --
const yarnB = `__metadata:
  version: 8

"left-pad@npm:^1.3.0":
  version: 1.3.0
  resolution: "left-pad@npm:1.3.0"
`;
r = parseLockfile(undefined, yarnB); // content sniff, no filename
T("berry sniff", r.format === "yarn");
T("berry name", r.packages.length === 1 && r.packages[0].name === "left-pad" && r.packages[0].version === "1.3.0", r.packages);

// -- 5. requirements.txt --
const reqs = `# comment
flask==3.0.0
requests[security]>=2.31  # inline comment
numpy ; python_version > "3.10"
-r other.txt
--index-url https://example.com
Django==4.2.7
`;
r = parseLockfile("requirements.txt", reqs);
T("req format", r.format === "requirements");
T("req count", r.packages.length === 4, r.packages);
T("req exact", r.packages.some((p) => p.name === "flask" && p.version === "3.0.0" && p.ecosystem === "PyPI"));
T("req unpinned", r.packages.some((p) => p.name === "requests" && p.version_source === "unpinned"));
T("req marker-name", r.packages.some((p) => p.name === "numpy" && p.version === undefined));

// -- 6. Pipfile.lock --
const pipfile = JSON.stringify({
  _meta: {},
  default: { flask: { version: "==3.0.0" } },
  develop: { pytest: { version: "==8.0.0" } },
});
r = parseLockfile("Pipfile.lock", pipfile);
T("pipfile format", r.format === "pipfile");
T("pipfile dev", r.packages.some((p) => p.name === "pytest" && p.dev === true && p.version === "8.0.0"));
T("pipfile prod", r.packages.some((p) => p.name === "flask" && !p.dev && p.version === "3.0.0"));

// -- 7. go.mod --
const gomod = `module example.com/app

go 1.22

require (
\tgithub.com/gin-gonic/gin v1.9.1
\tgithub.com/lib/pq v1.10.9 // indirect
)

require github.com/single/dep v0.5.0
`;
r = parseLockfile("go.mod", gomod);
T("gomod format", r.format === "go-mod");
T("gomod count", r.packages.length === 3, r.packages);
T("gomod indirect=dev", r.packages.some((p) => p.name === "github.com/lib/pq" && p.dev === true));
T("gomod eco", r.packages.every((p) => p.ecosystem === "Go"));

// -- 8. Cargo.lock --
const cargo = `# This file is automatically @generated by Cargo.
[[package]]
name = "serde"
version = "1.0.197"

[[package]]
name = "tokio"
version = "1.37.0"
`;
r = parseLockfile(undefined, cargo); // content sniff
T("cargo sniff", r.format === "cargo");
T("cargo pkgs", r.packages.length === 2 && r.packages[0].name === "serde" && r.packages[0].version === "1.0.197");
T("cargo eco", r.packages.every((p) => p.ecosystem === "crates.io"));

// -- 9. package.json (manifest, unpinned) --
const pjson = JSON.stringify({
  name: "app", version: "1.0.0",
  dependencies: { express: "^4.18.2" },
  devDependencies: { jest: "^29.0.0" },
});
r = parseLockfile("package.json", pjson);
T("pjson format", r.format === "package-json");
T("pjson manifest-src", r.packages.every((p) => p.version_source === "manifest" && p.version === undefined));
T("pjson dev", r.packages.some((p) => p.name === "jest" && p.dev === true));

// -- 10. content sniff without filename --
T("sniff package-lock", detectLockfileFormat(undefined, pl3) === "package-lock");
T("sniff package.json", detectLockfileFormat(undefined, pjson) === "package-json");
T("sniff go.mod", detectLockfileFormat(undefined, gomod) === "go-mod");
T("sniff requirements", detectLockfileFormat(undefined, reqs) === "requirements");
T("sniff pipfile", detectLockfileFormat(undefined, pipfile) === "pipfile");

// -- 11. negative controls --
r = parseLockfile("weird.txt", "this is not a lockfile at all\njust prose");
T("NC unknown format", r.error !== undefined && r.format === "unknown");
r = parseLockfile("package-lock.json", JSON.stringify({ lockfileVersion: 3, packages: { "": {} } }));
T("NC zero packages", r.error !== undefined && r.packages.length === 0);

// -- 12. merge: precedence, dedupe, cap --
const input = [{ name: "lodash", ecosystem: "npm", version: "9.9.9", version_source: "input" }];
const lock = [
  { name: "lodash", ecosystem: "npm", version: "9.9.9", version_source: "lockfile" }, // dup of input
  { name: "react", ecosystem: "npm", version: "18.2.0", version_source: "lockfile" },
];
const mani = [{ name: "react", ecosystem: "npm", version_source: "manifest" }]; // different version key → NOT deduped vs 18.2.0? version "" vs "18.2.0" differ
const m = mergePackageLists(input, lock, mani);
T("merge dedupe", m.packages.filter((p) => p.name === "lodash").length === 1);
T("merge order", m.packages[0].name === "lodash" && m.packages[0].version_source === "input");
const big = Array.from({ length: PACKAGES_MAX + 10 }, (_, i) => ({ name: `p${i}`, ecosystem: "npm", version: "1.0.0", version_source: "lockfile" }));
const m2 = mergePackageLists(big);
T("merge cap", m2.capped === true && m2.packages.length === PACKAGES_MAX);

// -- 13. determinism --
const a1 = JSON.stringify(parseLockfile("yarn.lock", yarn1));
const a2 = JSON.stringify(parseLockfile("yarn.lock", yarn1));
T("determinism", a1 === a2);

console.log(`\n${pass}/${pass + fail} PASS`);
process.exit(fail ? 1 : 0);
